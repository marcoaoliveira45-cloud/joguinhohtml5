create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  display_name text not null check (char_length(btrim(display_name)) between 1 and 20),
  score integer not null check (score between 0 and 1000000),
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;
grant select, insert on public.scores to anon;

drop policy if exists "Anyone can read scores" on public.scores;
create policy "Anyone can read scores"
  on public.scores for select to anon using (true);

drop policy if exists "Anyone can submit scores" on public.scores;
create policy "Anyone can submit scores"
  on public.scores for insert to anon
  with check (
    char_length(btrim(display_name)) between 1 and 20
    and score between 0 and 1000000
  );

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'scores'
  ) then
    execute 'alter publication supabase_realtime add table public.scores';
  end if;
end
$$;
